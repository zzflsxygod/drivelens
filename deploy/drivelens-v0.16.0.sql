-- DriveLens v0.16.0 (API 0.12.0, api_level 13): Web Push notifications (trip summary, monthly report reminder).
-- Only needed on servers where the drivelens tables were created by the database admin (older installs that ran
-- drivelens-init.sql / drivelens-v0.x.sql). Installs set up with setup.sql need nothing: the API creates these tables itself.
-- Creates two tables in the drivelens schema; TeslaMate's tables are not touched. Safe to re-run.
--   docker compose exec -T database psql -U teslamate -d teslamate < drivelens-v0.16.0.sql

-- 1) push subscriptions (one row per browser / device that enabled notifications)
CREATE TABLE IF NOT EXISTS drivelens.push_subscriptions (
  id bigserial PRIMARY KEY,
  endpoint text NOT NULL UNIQUE,            -- push service URL from the browser
  p256dh text NOT NULL,                     -- browser's public key (base64url)
  auth text NOT NULL,                       -- browser's auth secret (base64url)
  trip_summary boolean NOT NULL DEFAULT true,
  monthly_report boolean NOT NULL DEFAULT true,
  car_ids integer[],                        -- NULL = all cars
  tz text NOT NULL DEFAULT 'UTC',           -- IANA time zone of the device (for "the 1st of the month")
  locale text NOT NULL DEFAULT 'en' CHECK (locale IN ('zh', 'en', 'ja')),
  user_agent text,
  last_monthly text,                        -- YYYY-MM of the last monthly reminder
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  last_success_at timestamptz,
  last_error text,
  fail_count integer NOT NULL DEFAULT 0);

-- 2) notifier state: VAPID key generated by the API on first start, last notified drive
CREATE TABLE IF NOT EXISTS drivelens.push_state (
  key text PRIMARY KEY,
  value text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now());

-- 3) grants for the API role
GRANT SELECT, INSERT, UPDATE, DELETE ON drivelens.push_subscriptions, drivelens.push_state TO drivelens_ro;
GRANT USAGE, SELECT ON SEQUENCE drivelens.push_subscriptions_id_seq TO drivelens_ro;
