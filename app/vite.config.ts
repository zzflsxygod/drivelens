/**
 * Web/PWA target (`npm run build:web` = `vite build --mode web` → dist-web/):
 *  - injects manifest / apple / theme-color tags into index.html
 *  - emits manifest.webmanifest and sw.js; the service worker precaches exactly the built app shell
 *    (index.html + hashed assets + icons) and never touches cross-origin requests (API, map tiles).
 * The Tauri build (`npm run build` → dist/) gets none of this.
 */
function pwa(): Plugin {
  const NAME = "DriveLens";
  return {
    name: "drivelens-pwa",
    apply: "build",
    transformIndexHtml(html) {
      return html.replace("</head>", `  <meta name="description" content="DriveLens — a viewer for your own TeslaMate data (self-hosted drivelens-api)" />
  <meta name="theme-color" content="#f3f4f7" media="(prefers-color-scheme: light)" />
  <meta name="theme-color" content="#07080a" media="(prefers-color-scheme: dark)" />
  <meta name="color-scheme" content="light dark" />
  <meta name="referrer" content="no-referrer" />
  <link rel="manifest" href="/manifest.webmanifest" />
  <link rel="icon" href="/favicon.ico" sizes="any" />
  <link rel="icon" type="image/png" sizes="32x32" href="/icons/favicon-32.png" />
  <link rel="apple-touch-icon" href="/icons/apple-touch-icon.png" />
  <meta name="mobile-web-app-capable" content="yes" />
  <meta name="apple-mobile-web-app-capable" content="yes" />
  <meta name="apple-mobile-web-app-title" content="${NAME}" />
  <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />
</head>`);
    },
    generateBundle(_o, bundle) {
      const manifest = {
        id: "/", name: NAME, short_name: NAME,
        description: "TeslaMate drives, charges, journeys and reports — connects to your own drivelens-api server.",
        start_url: "/?source=pwa", scope: "/", display: "standalone", display_override: ["standalone", "minimal-ui"],
        orientation: "portrait", background_color: "#f3f4f7", theme_color: "#f3f4f7",
        lang: "en", dir: "ltr", categories: ["utilities", "travel", "productivity"],
        icons: [
          { src: "/icons/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
          { src: "/icons/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
          { src: "/icons/maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
        ],
      };
      this.emitFile({ type: "asset", fileName: "manifest.webmanifest", source: JSON.stringify(manifest, null, 2) });
      // app shell = everything Vite emitted (hashed JS/CSS chunks incl. the lazy demo + maplibre chunks) + public icons
      const files = Object.keys(bundle).filter(f => !f.endsWith(".map"));
      const shell = ["/", ...files.map(f => "/" + f), "/manifest.webmanifest", "/favicon.ico",
        "/icons/icon-192.png", "/icons/icon-512.png", "/icons/maskable-512.png", "/icons/apple-touch-icon.png", "/icons/favicon-32.png", "/icons/badge-96.png"]
        .filter((v, i, a) => a.indexOf(v) === i && v !== "/index.html");
      this.emitFile({ type: "asset", fileName: "sw.js", source: swSource(`drivelens-shell-${pkg.version}-${Date.now().toString(36)}`, shell) });
    },
  };
}

/** Service worker: app shell only. API calls go to the user's own (cross-origin) server with a bearer token
 *  and are never intercepted or cached; same for map tiles. */
function swSource(cache: string, shell: string[]) {
  return `// DriveLens service worker (generated by vite.config.ts) — caches the app shell only.
const CACHE = ${JSON.stringify(cache)};
const SHELL = ${JSON.stringify(shell)};
self.addEventListener("install", e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL.map(u => new Request(u, { cache: "reload" }))))); });
self.addEventListener("activate", e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith("drivelens-shell-") && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener("message", e => { if (e.data === "skipWaiting") self.skipWaiting(); });
self.addEventListener("fetch", e => {
  const r = e.request;
  if (r.method !== "GET") return;
  const u = new URL(r.url);
  if (u.origin !== self.location.origin) return;            // user's API server, map tiles: straight to the network, never cached
  if (r.headers.has("authorization")) return;               // belt and braces: never cache anything carrying a token
  if (u.pathname === "/health" || u.pathname.startsWith("/api/")) return;
  // an address carrying api / token / key parameters is answered from the cached shell, never sent over the network
  // (so it cannot end up in any request log); the page itself strips them (src/urlguard.ts)
  if (r.mode === "navigate" && [...u.searchParams.keys()].some(k => ["api", "token", "key"].includes(k.toLowerCase()))) {
    e.respondWith(caches.match("/").then(hit => hit || fetch("/")));
    return;
  }
  if (r.mode === "navigate") {                              // SPA: always the cached shell (network first, so updates show up)
    e.respondWith(fetch(r).then(res => res.ok ? res : caches.match("/")).catch(() => caches.match("/")));
    return;
  }
  if (!SHELL.includes(u.pathname)) return;
  e.respondWith(caches.match(u.pathname).then(hit => hit || fetch(r)));
});
// Web Push (drivelens-api ≥ 0.12.0): the server sends {title, body, tag, url, kind}; nothing is cached here.
self.addEventListener("push", e => {
  let d = {};
  try { d = e.data ? e.data.json() : {}; } catch (_) { d = { body: e.data ? e.data.text() : "" }; }
  e.waitUntil(self.registration.showNotification(d.title || "DriveLens", {
    body: d.body || "", tag: d.tag || undefined, icon: "/icons/icon-192.png", badge: "/icons/badge-96.png",
    data: { url: typeof d.url === "string" ? d.url : "/" }, timestamp: Date.now() }));
});
self.addEventListener("notificationclick", e => {
  e.notification.close();
  const url = new URL((e.notification.data && e.notification.data.url) || "/", self.location.origin);
  if (url.origin !== self.location.origin) return;
  e.waitUntil((async () => {
    const wins = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
    const w = wins.find(c => new URL(c.url).origin === self.location.origin);
    const view = url.searchParams.get("view");
    if (w) {                                                 // app already open: focus it and let it navigate (no reload)
      await w.focus().catch(() => {});
      w.postMessage({ type: "drivelens-open", view });
      return;
    }
    url.searchParams.set("from", "push");
    await self.clients.openWindow(url.pathname + url.search);
  })());
});
`;
}

/**
 * Emits third-party-licenses.txt: name, version, license and the full license text of every npm package whose code
 * ends up in the bundle (collected from the modules Vite actually bundled, so dev-only tools are never listed).
 * Served by the web app at /third-party-licenses.txt (linked from Settings → About).
 */
function thirdPartyLicenses(): Plugin {
  const pkgDir = (id: string) => {
    const i = id.lastIndexOf(`${sep}node_modules${sep}`); if (i < 0) return null;
    const rest = id.slice(i + 14).split(sep);
    return id.slice(0, i + 14) + (rest[0].startsWith("@") ? join(rest[0], rest[1]) : rest[0]);
  };
  return {
    name: "drivelens-third-party-licenses",
    apply: "build",
    generateBundle(_o, bundle) {
      const dirs = new Set<string>();
      for (const c of Object.values(bundle)) if (c.type === "chunk") for (const id of Object.keys(c.modules)) { const d = pkgDir(id.replace(/^\0/, "").split("?")[0]); if (d) dirs.add(d); }
      const out = [`Third-party software in the DriveLens app ${pkg.version} (npm packages bundled into this build)`,
        "DriveLens itself is licensed under the GNU AGPL-3.0-or-later; source: https://github.com/zzflsxygod/drivelens", ""];
      const seen = new Set<string>();
      for (const d of [...dirs].sort()) {
        if (!existsSync(join(d, "package.json"))) continue;
        const p = JSON.parse(readFileSync(join(d, "package.json"), "utf8"));
        if (seen.has(`${p.name}@${p.version}`)) continue; seen.add(`${p.name}@${p.version}`);
        const lic = readdirSync(d).filter(f => /^(licen[cs]e|copying|notice)/i.test(f) && !/\.spdx$/i.test(f)).sort();
        out.push("-".repeat(80), `${p.name} ${p.version} — ${p.license ?? "see below"}${p.repository ? ` — ${typeof p.repository === "string" ? p.repository : p.repository.url}` : ""}`, "-".repeat(80),
          lic.length ? lic.map(f => readFileSync(join(d, f), "utf8").trim()).join("\n\n") : `(no license file in the package; license field: ${p.license})`, "");
      }
      // demo map data shipped with the app
      out.push("-".repeat(80), "Demo routes (src/demo/routes.json)", "-".repeat(80),
        "Routes © OpenStreetMap contributors, Open Database License (ODbL) 1.0 — https://www.openstreetmap.org/copyright",
        "Elevation: Copernicus DEM via Open-Meteo, CC BY 4.0 — https://open-meteo.com/en/license", "");
      this.emitFile({ type: "asset", fileName: "third-party-licenses.txt", source: out.join("\n") });
    },
  };
}

export default defineConfig(({ mode }) => {
  const web = mode === "web";
  return {
    clearScreen: false,
    define: { __APP_VERSION__: JSON.stringify(pkg.version), __WEB_BUILD__: JSON.stringify(web), __WEB_ORIGIN__: JSON.stringify(WEB_ORIGIN) },
    server: { port: 1420, strictPort: true, host: host || false,
      hmr: host ? { protocol: "ws", host, port: 1421 } : undefined },
    envPrefix: ["VITE_", "TAURI_ENV_*"],
    publicDir: web ? "web-public" : false,
    plugins: web ? [thirdPartyLicenses(), pwa()] : [thirdPartyLicenses()],
    build: { target: "es2020", outDir: web ? "dist-web" : "dist", emptyOutDir: true },
  };
});
